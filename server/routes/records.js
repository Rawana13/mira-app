const express = require('express');
const Anthropic = require('@anthropic-ai/sdk');
const PDFDocument = require('pdfkit');
const { getRecordsSummaryPrompt } = require('../prompts/records');

const router = express.Router();
const anthropic = new Anthropic({ apiKey: process.env.ANTHROPIC_API_KEY });

const LANG_NAMES = {
  en: 'English', hi: 'Hindi', zh: 'Simplified Chinese', ko: 'Korean', ar: 'Arabic',
};

router.post('/generate-pdf', async (req, res) => {
  const { entries, language, userName } = req.body;
  if (!entries?.length) {
    return res.status(400).json({ message: 'No entries provided' });
  }

  const langName = LANG_NAMES[language] || 'English';

  try {
    // Get AI-generated structured summary
    const message = await anthropic.messages.create({
      model: 'claude-sonnet-4-20250514',
      max_tokens: 2048,
      system: getRecordsSummaryPrompt(langName, entries, userName || 'Patient'),
      messages: [{ role: 'user', content: 'Generate the health records summary document.' }],
    });

    const rawText = message.content[0].text.trim();
    const jsonMatch = rawText.match(/\{[\s\S]*\}/);
    if (!jsonMatch) throw new Error('No JSON found in response');

    const summary = JSON.parse(jsonMatch[0]);

    // Generate PDF
    const doc = new PDFDocument({ margin: 50, size: 'A4' });
    const chunks = [];
    doc.on('data', (chunk) => chunks.push(chunk));
    doc.on('end', () => {
      const pdfBuffer = Buffer.concat(chunks);
      res.set({
        'Content-Type': 'application/pdf',
        'Content-Disposition': `attachment; filename="mira-health-records.pdf"`,
        'Content-Length': pdfBuffer.length,
      });
      res.send(pdfBuffer);
    });

    // Cover page
    doc.fontSize(28).fillColor('#0D1B2A').text('Mira', { align: 'center' });
    doc.fontSize(16).fillColor('#2E86AB').text(summary.document_title || 'Healthcare Records Summary', { align: 'center' });
    doc.moveDown();
    doc.fontSize(12).fillColor('#1B3A5C').text(`Patient: ${summary.patient_name}`, { align: 'center' });
    doc.text(`Generated: ${summary.generated_date}`, { align: 'center' });

    doc.moveDown(2);
    doc.fontSize(10).fillColor('#555').text(
      'This document was prepared by Mira to help communicate healthcare information across borders.',
      { align: 'center' }
    );

    // US System note
    if (summary.us_system_note) {
      doc.addPage();
      doc.fontSize(14).fillColor('#0D1B2A').text('About the US Healthcare System', { underline: true });
      doc.moveDown(0.5);
      doc.fontSize(11).fillColor('#333').text(summary.us_system_note, { lineGap: 4 });
    }

    // Visit history
    if (summary.visit_history?.length > 0) {
      doc.addPage();
      doc.fontSize(14).fillColor('#0D1B2A').text('Visit History', { underline: true });
      doc.moveDown(0.5);
      summary.visit_history.forEach((visit) => {
        doc.fontSize(11).fillColor('#1B3A5C').text(`${visit.date} — ${visit.type.toUpperCase()}`);
        doc.fontSize(10).fillColor('#333').text(visit.summary, { lineGap: 3 });
        doc.moveDown(0.5);
      });
    }

    // Current medications
    if (summary.current_medications?.length > 0) {
      doc.addPage();
      doc.fontSize(14).fillColor('#0D1B2A').text('Current Medications', { underline: true });
      doc.moveDown(0.5);
      summary.current_medications.forEach((med) => {
        doc.fontSize(11).fillColor('#333').text(`• ${med}`, { lineGap: 3 });
      });
    }

    // Outstanding follow-ups
    if (summary.outstanding_followups?.length > 0) {
      doc.moveDown(1.5);
      doc.fontSize(14).fillColor('#0D1B2A').text('Outstanding Follow-ups', { underline: true });
      doc.moveDown(0.5);
      summary.outstanding_followups.forEach((f) => {
        doc.fontSize(11).fillColor('#333').text(`• ${f}`, { lineGap: 3 });
      });
    }

    // Lab results
    if (summary.lab_results?.length > 0) {
      doc.moveDown(1.5);
      doc.fontSize(14).fillColor('#0D1B2A').text('Lab Results', { underline: true });
      doc.moveDown(0.5);
      summary.lab_results.forEach((lab) => {
        doc.fontSize(11).fillColor('#333').text(`• ${lab}`, { lineGap: 3 });
      });
    }

    // Footer on last page
    doc.moveDown(2);
    doc.fontSize(9).fillColor('#999').text(
      'Generated by Mira — Healthcare Companion for International Students',
      { align: 'center' }
    );

    doc.end();
  } catch (err) {
    console.error('PDF generation error:', err.message);
    res.status(500).json({ message: 'Unable to generate PDF. Please try again.' });
  }
});

module.exports = router;
